import { useState, type FormEvent } from 'react';
import { useMutation } from '@tanstack/react-query';
import type { AskResult } from '../../shared/contracts';
import { api, type ApiError } from '../api';
import { Button, Card } from '../design/components';

function describe(result: AskResult): string {
  switch (result.status) {
    case 'answered':
      return result.answer;
    case 'blocked':
      return 'The content filter blocked this question or its answer. Rephrase it and try again.';
    case 'try-later':
      return result.reason === 'limit'
        ? `You have reached your hourly limit. Try again in about ${Math.ceil(result.retryAfterSeconds / 60)} minutes.`
        : `The AI service is busy. Try again in ${result.retryAfterSeconds} seconds.`;
    case 'not-configured':
      return 'AI is not configured here. Set the Foundry endpoint and the deployment name in the settings.';
  }
}

export function AskPage() {
  const [question, setQuestion] = useState('');
  const ask = useMutation({ mutationFn: (q: string) => api<AskResult>('/api/ai/ask', { method: 'POST', body: { question: q } }) });

  const submit = (e: FormEvent) => {
    e.preventDefault();
    if (question.trim()) ask.mutate(question);
  };

  return (
    <>
      <h2>Ask AI</h2>
      <p className="app-notice">
        You are talking to an AI. Answers can be wrong: check them before you rely on them. Do not enter personal data.
      </p>
      <Card variant="outlined">
        <form className="app-form" onSubmit={submit}>
          <label className="itm8-field__label" htmlFor="question">
            Your question
          </label>
          <textarea
            id="question"
            className="itm8-input"
            rows={4}
            maxLength={2000}
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
          />
          <Button type="submit" disabled={ask.isPending}>
            {ask.isPending ? 'Thinking…' : 'Ask'}
          </Button>
        </form>
      </Card>
      {ask.data ? (
        <Card variant="muted" className="app-answer">
          {ask.data.status === 'answered' ? <p className="itm8-overline">Generated by AI</p> : null}
          <p>{describe(ask.data)}</p>
        </Card>
      ) : null}
      {ask.error ? <p role="alert">Error: {(ask.error as ApiError).message}</p> : null}
    </>
  );
}
